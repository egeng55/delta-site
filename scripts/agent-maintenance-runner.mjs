#!/usr/bin/env node

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import {
  classifyFindings,
  readFindings,
  readPolicy,
  repoRoot,
  selectTopActionable,
} from "./agent-policy.mjs";

const runsDir = path.join(repoRoot, "agent", "runs");

function parseArgs(argv) {
  const values = {
    report: false,
    json: false,
    write: false,
    force: false,
    includeBriefCommand: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--report") values.report = true;
    else if (arg === "--json") values.json = true;
    else if (arg === "--write") values.write = true;
    else if (arg === "--force") values.force = true;
    else if (arg === "--include-brief-command") values.includeBriefCommand = true;
  }

  return values;
}

function runGit(args) {
  const result = spawnSync("git", args, {
    cwd: repoRoot,
    encoding: "utf8",
    shell: false,
  });
  if (result.error) return "";
  return (result.stdout || result.stderr || "").trim();
}

function timestampForRun() {
  return new Date().toISOString().replace(/\.\d{3}Z$/, "Z").replace(/:/g, "-");
}

function countBy(items, getKey) {
  const counts = {};
  for (const item of items) {
    const key = getKey(item) || "unknown";
    counts[key] = (counts[key] || 0) + 1;
  }
  return counts;
}

function list(items) {
  if (!items || items.length === 0) return "- none";
  return items.map((item) => `- ${item}`).join("\n");
}

function approvalRequirementFor(policy) {
  if (!policy) return "No policy-allowed finding is currently selected.";
  if (policy.actionMode === "human_required") return "Human/provider action is required.";
  if (policy.actionMode === "implementation_requires_approval") {
    return "Human approval is required before implementation or runtime changes.";
  }
  if (policy.actionMode === "docs_eval_autofix_allowed") {
    return "Docs/eval-only work still needs scoped phase approval and human merge review.";
  }
  if (policy.actionMode === "blocked") return "Action is blocked by policy.";
  return "Follow the selected policy mode before planning or editing.";
}

function buildSummary() {
  const timestamp = timestampForRun();
  const runId = `${timestamp}-maintenance-cycle`;
  const branch = runGit(["branch", "--show-current"]) || "unknown";
  const head = runGit(["rev-parse", "--short", "HEAD"]);
  const gitStatus = runGit(["status", "--short"]);
  const repoClean = gitStatus.length === 0;
  const policy = readPolicy();
  const findings = readFindings();
  const classified = classifyFindings(findings, policy);
  const top = selectTopActionable(classified);
  const selected = top.selected;
  const selectedFinding = selected?.finding || null;
  const selectedPolicy = selected?.policy || null;
  const findingBriefCommand = selectedFinding
    ? `npm run agent:finding:brief -- --id ${selectedFinding.id} --phase <number> --name ${selectedFinding.slug || "<slug>"}`
    : null;
  const recommendedNextCommand = findingBriefCommand || "npm run agent:maintenance -- --report";
  const blockedCategories = classified
    .filter(({ policy: findingPolicy }) => ["blocked", "human_required"].includes(findingPolicy.actionMode))
    .map(({ finding, policy: findingPolicy }) => `${finding.id} ${finding.title}: ${findingPolicy.actionMode}`);
  const refusedActions = [
    "No maintenance finding was implemented.",
    "No phase brief file was generated by this runner.",
    "No worktree was created.",
    "No tests or services were run by this runner.",
    "No Supabase, mic, TTS, notification, or product memory/write action was run.",
    "No autonomous merge, branch cleanup, or npm audit fix was run.",
  ];

  return {
    runId,
    timestamp,
    generatedBy: "scripts/agent-maintenance-runner.mjs",
    reportOnlyDefault: true,
    wroteFile: false,
    repo: {
      root: repoRoot,
      branch,
      head,
      clean: repoClean,
      status: gitStatus || "(clean)",
    },
    counts: {
      byStatus: countBy(classified, ({ finding }) => finding.status),
      byPriority: countBy(classified, ({ finding }) => finding.priority),
      byPolicyMode: countBy(classified, ({ policy: findingPolicy }) => findingPolicy.actionMode),
    },
    findings: classified.map(({ finding, policy: findingPolicy }) => ({
      id: finding.id,
      title: finding.title,
      priority: finding.priority,
      status: finding.status,
      repo: finding.repo,
      routine: finding.routine,
      policyMode: findingPolicy.actionMode,
      policyReason: findingPolicy.reason,
    })),
    topActionable: selected
      ? {
          id: selectedFinding.id,
          title: selectedFinding.title,
          priority: selectedFinding.priority,
          status: selectedFinding.status,
          repo: selectedFinding.repo,
          routine: selectedFinding.routine,
          policyMode: selectedPolicy.actionMode,
          policyReason: selectedPolicy.reason,
          selectionRationale: top.rationale,
        }
      : {
          selectionRationale: top.rationale,
        },
    approvalRequirement: approvalRequirementFor(selectedPolicy),
    allowedNextActions: selectedPolicy?.allowedNextCommands || [],
    forbiddenActions: selectedPolicy?.forbiddenActions || [],
    blockedCategories,
    refusedActions,
    recommendedNextCommand,
    findingBriefCommand,
    notes: [
      "Report-only maintenance cycle completed.",
      "No implementation was performed.",
      "This cycle report is operational metadata for future agents.",
      "It does not replace human approval or verification.",
    ],
  };
}

function renderMarkdown(summary) {
  return `# Agent Maintenance Cycle ${summary.runId}

Generated by: \`scripts/agent-maintenance-runner.mjs\`

This is a report-only maintenance cycle. It inspected local findings, applied
maintenance policy, selected the next policy-allowed finding, and stopped. It
does not implement findings, generate phase brief files, create worktrees, run
tests, call services, or change product behavior.

## Run Identity

- Run id: ${summary.runId}
- Timestamp: ${summary.timestamp}
- Repo root: ${summary.repo.root}
- Branch: ${summary.repo.branch}
- HEAD: ${summary.repo.head}
- Repo clean: ${summary.repo.clean ? "yes" : "no"}

## Repo Status

\`\`\`text
${summary.repo.status}
\`\`\`

## Findings Summary

By status:
${list(Object.entries(summary.counts.byStatus).map(([key, value]) => `${key}: ${value}`))}

By priority:
${list(Object.entries(summary.counts.byPriority).map(([key, value]) => `${key}: ${value}`))}

## Policy Summary

By policy mode:
${list(Object.entries(summary.counts.byPolicyMode).map(([key, value]) => `${key}: ${value}`))}

Blocked or human-required categories:
${list(summary.blockedCategories)}

## Top Actionable Finding

- Finding id: ${summary.topActionable.id || "none"}
- Title: ${summary.topActionable.title || "none"}
- Priority: ${summary.topActionable.priority || "none"}
- Status: ${summary.topActionable.status || "none"}
- Repo: ${summary.topActionable.repo || "none"}
- Routine: ${summary.topActionable.routine || "none"}
- Policy mode: ${summary.topActionable.policyMode || "none"}
- Policy reason: ${summary.topActionable.policyReason || "none"}
- Selection rationale: ${summary.topActionable.selectionRationale}

## Approval Requirement

- ${summary.approvalRequirement}

## Allowed Next Actions

${list(summary.allowedNextActions)}

## Forbidden Actions

${list(summary.forbiddenActions)}

## Refused Actions

${list(summary.refusedActions)}

## Recommended Next Command

\`\`\`bash
${summary.recommendedNextCommand}
\`\`\`

${summary.findingBriefCommand ? `Suggested finding-to-brief command:

\`\`\`bash
${summary.findingBriefCommand}
\`\`\`
` : ""}
## Finding Snapshot

${summary.findings.map((finding) => `- ${finding.id} [${finding.priority}] ${finding.status}: ${finding.title} (${finding.policyMode})`).join("\n")}

## Product Behavior

- No product behavior changed.
- No /os runtime behavior changed.
- No backend runtime behavior changed.
- No mobile runtime behavior changed.
- No Supabase/mic/TTS/notification/product-memory/write actions ran.
`;
}

function printReport(summary, args) {
  console.log("Delta report-only maintenance runner");
  console.log("====================================");
  console.log("Mode: report-only by default. No files are written unless --write is passed.");
  console.log("");
  console.log(`Run id: ${summary.runId}`);
  console.log(`HEAD: ${summary.repo.head}`);
  console.log(`Repo clean: ${summary.repo.clean ? "yes" : "no"}`);
  console.log("");
  console.log("Findings summary:");
  for (const [key, count] of Object.entries(summary.counts.byStatus).sort()) {
    console.log(`- ${key}: ${count}`);
  }
  console.log("");
  console.log("Policy summary:");
  for (const [mode, count] of Object.entries(summary.counts.byPolicyMode).sort()) {
    console.log(`- ${mode}: ${count}`);
  }
  console.log("");
  console.log("Top actionable finding:");
  console.log(`- id: ${summary.topActionable.id || "none"}`);
  console.log(`- title: ${summary.topActionable.title || "none"}`);
  console.log(`- policy mode: ${summary.topActionable.policyMode || "none"}`);
  console.log(`- approval: ${summary.approvalRequirement}`);
  console.log(`- rationale: ${summary.topActionable.selectionRationale}`);
  console.log("");
  console.log("Recommended next command:");
  console.log(summary.recommendedNextCommand);
  if (args.includeBriefCommand && summary.findingBriefCommand) {
    console.log("");
    console.log("Suggested finding-to-brief command:");
    console.log(summary.findingBriefCommand);
  }
  console.log("");
  console.log("Blocked or human-required categories:");
  for (const category of summary.blockedCategories.length > 0 ? summary.blockedCategories : ["none"]) {
    console.log(`- ${category}`);
  }
  console.log("");
  console.log("Refused actions:");
  for (const action of summary.refusedActions) console.log(`- ${action}`);
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const summary = buildSummary();
  const targetPath = path.join(runsDir, `${summary.runId}.md`);
  summary.targetPath = path.relative(repoRoot, targetPath);

  if (args.write) {
    if (existsSync(targetPath) && !args.force) {
      const message = `Refusing to overwrite existing maintenance cycle report: ${summary.targetPath}. Use --force intentionally.`;
      if (args.json) process.stdout.write(`${JSON.stringify({ ...summary, error: message }, null, 2)}\n`);
      else console.error(message);
      process.exit(1);
    }
    mkdirSync(runsDir, { recursive: true });
    writeFileSync(targetPath, renderMarkdown(summary), "utf8");
    summary.wroteFile = true;
  }

  if (args.json) {
    process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`);
    return;
  }

  printReport(summary, args);
  if (args.write) {
    console.log("");
    console.log(`Maintenance cycle report written: ${summary.targetPath}`);
  } else {
    console.log("");
    console.log("Print-only: no files written. Add --write to create a maintenance cycle report.");
  }
}

main();
